"""
Generates a C++ trait header and a Make include from generalized out_mul_type/
acc_mul_type blocks in L2/meta/type_promotions.json.

Usage: gen_mul_types.py <xf_dsp_path>
"""
import json
import os
import sys


def gen_cpp_specializations(table, struct_name):
    lines = []
    for a, row in table.items():
        for b, out in row.items():
            lines.append("template <>")
            lines.append(f"struct {struct_name}<{a}, {b}> {{")
            lines.append(f"    using type = {out};")
            lines.append("};")
    return lines


def gen_cpp_header(family, out_mul_type, acc_mul_type):
    # Each promotion family lives in its own namespace so that mul and mac headers can be
    # included in the same translation unit (their accType tables differ).
    lines = [
        "// Generated by gen_mul_types.py. Do not edit by hand.",
        "#pragma once", "", "namespace xf {", "namespace dsp {", "namespace aie {",
        f"namespace promotions_{family} {{", ""]

    lines.append("// determine the type depending on the input type combinations")
    lines.append("template <typename T_A, typename T_B> struct outType;")
    lines += gen_cpp_specializations(out_mul_type, "outType")
    lines.append("")
    lines.append("template <typename T_D_A, typename T_D_B>")
    lines.append("using outType_t = typename outType<T_D_A, T_D_B>::type;")
    lines.append("")

    lines.append("// determine the acc type depending on the input type combinations")
    lines.append("template <typename T_A, typename T_B> struct accType;")
    lines.append("#ifdef __SUPPORTS_ACC64__")
    lines += gen_cpp_specializations(acc_mul_type["acc64"], "accType")
    lines.append("#else")
    lines += gen_cpp_specializations(acc_mul_type["acc48"], "accType")
    lines.append("#endif")
    lines.append("")
    lines.append("template <typename T_D_A, typename T_D_B>")
    lines.append("using accType_t = typename accType<T_D_A, T_D_B>::type;")

    lines += ["}", "}", "}", "}"]
    return "\n".join(lines) + "\n"


def gen_make_include(out_mul_type):
    lines = ["# Generated by gen_mul_types.py. Do not edit by hand."]

    for a, row in out_mul_type.items():
        for b, out in row.items():
            lines.append(f"OUT_MUL_TYPE_{a}_{b} := {out}")
    lines.append("fn_det_out_type = $(OUT_MUL_TYPE_$(1)_$(2))")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    xf_dsp_path = sys.argv[1]

    L1_INCLUDE_DIR = os.path.join(xf_dsp_path, "L1/include/aie")
    L2_COMMON_SCRIPTS_DIR = os.path.join(xf_dsp_path, "L2/tests/aie")
    TYPE_PROMOTION_PATH = os.path.join(xf_dsp_path, "L2/meta/type_promotions.json")

    with open(TYPE_PROMOTION_PATH, "r") as f:
        data = json.load(f)
    out_mul_type = data["out_mul_type"]
    acc_mul_type = data["acc_mul_type"]
    acc_mac_type = data["acc_mac_type"]

    hpp_mul_path = os.path.join(L1_INCLUDE_DIR, f"promotions_mul.hpp")
    with open(hpp_mul_path, "w") as f:
        f.write(gen_cpp_header("mul", out_mul_type, acc_mul_type))
    print(f"Wrote {hpp_mul_path}")

    hpp_mac_path = os.path.join(L1_INCLUDE_DIR, f"promotions_mac.hpp")
    with open(hpp_mac_path, "w") as f:
        f.write(gen_cpp_header("mac", out_mul_type, acc_mac_type))
    print(f"Wrote {hpp_mac_path}")

    mk_path = os.path.join(L2_COMMON_SCRIPTS_DIR, "out_mul_types.mk")
    with open(mk_path, "w") as f:
        f.write(gen_make_include(out_mul_type))
    print(f"Wrote {mk_path}")
